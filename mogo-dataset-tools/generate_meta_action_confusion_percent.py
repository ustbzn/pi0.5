#!/usr/bin/env python3
"""Generate a percentage confusion-matrix image from existing meta_action metrics."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib.pyplot as plt


DEFAULT_METRICS_CSV = Path(
    "/pcpt/pcpt/data/VLA/MOGO/meta_action_test_pipeline/"
    "20260511_after_processed_ali/metrics_all.csv"
)


def parse_bool(value: str) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def load_records(metrics_csv: Path) -> list[dict[str, str]]:
    with metrics_csv.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        return list(reader)


def build_labels(records: list[dict[str, str]]) -> list[str]:
    labels = {
        str(record.get("raw_meta_action", "")).strip()
        for record in records
        if str(record.get("raw_meta_action", "")).strip()
    }
    labels.update(
        {
            str(record.get("final_meta_action", "")).strip()
            for record in records
            if str(record.get("final_meta_action", "")).strip()
        }
    )
    return sorted(labels)


def build_count_matrix(
    records: list[dict[str, str]],
    labels: list[str],
) -> list[list[int]]:
    index = {label: i for i, label in enumerate(labels)}
    matrix = [[0 for _ in labels] for _ in labels]
    for record in records:
        raw_action = str(record.get("raw_meta_action", "")).strip()
        final_action = str(record.get("final_meta_action", "")).strip()
        if not raw_action or not final_action:
            continue
        if raw_action not in index or final_action not in index:
            continue
        matrix[index[raw_action]][index[final_action]] += 1
    return matrix


def row_normalize(matrix: list[list[int]]) -> list[list[float]]:
    percent_matrix: list[list[float]] = []
    for row in matrix:
        row_total = sum(row)
        if row_total == 0:
            percent_matrix.append([0.0 for _ in row])
            continue
        percent_matrix.append([(value / row_total) * 100.0 for value in row])
    return percent_matrix


def filter_records(
    records: list[dict[str, str]],
    subset: str,
) -> list[dict[str, str]]:
    if subset == "all":
        return records
    if subset == "original_target":
        return [
            record
            for record in records
            if parse_bool(record.get("is_original_target", "False"))
        ]
    raise ValueError(f"unsupported subset: {subset}")


def infer_default_output_path(metrics_csv: Path, subset: str) -> Path:
    suffix = "all" if subset == "all" else "original_target"
    return metrics_csv.parent / f"confusion_{suffix}_percent.png"


def save_confusion_percent_png(
    records: list[dict[str, str]],
    output_path: Path,
    title: str,
) -> None:
    labels = build_labels(records)
    if not labels:
        raise ValueError("no valid labels found in records")

    count_matrix = build_count_matrix(records, labels)
    percent_matrix = row_normalize(count_matrix)

    size = max(8, min(22, 0.55 * len(labels) + 5))
    fig, ax = plt.subplots(figsize=(size, size))
    image = ax.imshow(percent_matrix, cmap="Blues", vmin=0.0, vmax=100.0)
    ax.set_title(title)
    ax.set_xlabel("pred final meta_action")
    ax.set_ylabel("raw meta_action")
    ax.set_xticks(range(len(labels)))
    ax.set_yticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=8)
    ax.set_yticklabels(labels, fontsize=8)

    for row_idx, row in enumerate(percent_matrix):
        for col_idx, value in enumerate(row):
            if value <= 0:
                continue
            color = "white" if value >= 55.0 else "black"
            ax.text(
                col_idx,
                row_idx,
                f"{value:.1f}%",
                ha="center",
                va="center",
                color=color,
                fontsize=9,
            )

    colorbar = fig.colorbar(image, ax=ax, fraction=0.046, pad=0.04)
    colorbar.set_label("Percentage (%)")

    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate a row-normalized confusion matrix whose annotations are "
            "percentages."
        )
    )
    parser.add_argument(
        "--metrics-csv",
        type=Path,
        default=DEFAULT_METRICS_CSV,
        help="Existing metrics_all.csv generated by run_meta_action_test_pipeline.py.",
    )
    parser.add_argument(
        "--subset",
        choices=["all", "original_target"],
        default="all",
        help="Which subset of metrics_all.csv to visualize.",
    )
    parser.add_argument(
        "--output-path",
        type=Path,
        default=None,
        help="Output image path. Defaults to confusion_<subset>_percent.png next to the csv.",
    )
    parser.add_argument(
        "--title",
        default=None,
        help="Custom figure title.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    metrics_csv = args.metrics_csv.resolve()
    if not metrics_csv.is_file():
        raise FileNotFoundError(f"metrics csv not found: {metrics_csv}")

    records = load_records(metrics_csv)
    records = filter_records(records, args.subset)
    if not records:
        raise ValueError(f"no records available for subset={args.subset}")

    output_path = (
        args.output_path.resolve()
        if args.output_path is not None
        else infer_default_output_path(metrics_csv, args.subset)
    )
    title = args.title or (
        "All Samples (%)" if args.subset == "all" else "Original Target Samples (%)"
    )

    save_confusion_percent_png(records, output_path, title)
    print(f"[DONE] saved confusion matrix to: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
