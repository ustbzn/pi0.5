"""
Convert JSON files generated by drivepi_nusc_data_converter.py to pkl format for drive-π0 training.
Only converts fields that exist in JSON, with field name alignment.

python /D2/NXT/vlm/miaobinqi/Senna/data_tools_pi0/json_to_pkl_converter.py \
  /D2/NXT/vlm/miaobinqi/DriveMoE/datasets/nuscene-0109/train_json \
  --output /D2/NXT/vlm/miaobinqi/DriveMoE/datasets/nuscene-0109/train \
  --recursive

python /D2/NXT/vlm/miaobinqi/Senna/data_tools_pi0/json_to_pkl_converter.py \
  /D2/NXT/vlm/miaobinqi/DriveMoE/datasets/nuscene-0109/val_json \
  --output /D2/NXT/vlm/miaobinqi/DriveMoE/datasets/nuscene-0109/val \
  --recursive
"""

import json
import pickle
import numpy as np
import os
from pathlib import Path
import tensorflow as tf
from tqdm import tqdm

# Field name mapping: JSON field name -> pkl field name
FIELD_MAPPING = {
    'his_theta': 'his_theta',
    'his_speed': 'his_speed',
    'his_acceleration': 'his_acceleration',
    'his_angular_velocity': 'his_angular_velocity',
    'navigation_x': 'x_command_far',
    'navigation_y': 'y_command_far',
    'meta_action_x': 'x_command_near',
    'meta_action_y': 'y_command_near',
    'future_x': 'fur_x',
    'future_y': 'fur_y',
}

def convert_json_to_pkl(json_path, output_path=None):
    """
    Convert a single JSON file to pkl format.
    Only converts fields that exist in JSON, with field name alignment.
    
    Args:
        json_path: Path to input JSON file
        output_path: Path to output pkl file (if None, use same name with .pkl extension)
    """
    # Load JSON data
    with open(json_path, 'r') as f:
        json_data = json.load(f)
    
    if not json_data or len(json_data) == 0:
        raise ValueError(f"Empty JSON file: {json_path}")
    
    data = json_data[0]  # JSON is a list with one dict
    
    # Create pkl data structure
    pkl_data = {}
    
    # Convert fields that exist in JSON (mapped fields)
    mapped_keys = set()
    for json_key, pkl_key in FIELD_MAPPING.items():
        if json_key in data:
            value = data[json_key]
            # Convert to numpy array with appropriate dtype
            if isinstance(value, list):
                arr = np.array(value, dtype=np.float32)
                pkl_data[pkl_key] = arr
            else:
                pkl_data[pkl_key] = value
            mapped_keys.add(json_key)
    
    # Add all other fields from JSON that are not mapped (keep original field names)
    excluded_fields = {'images', 'his_images'}  # These are handled separately
    for json_key, value in data.items():
        if json_key not in mapped_keys and json_key not in excluded_fields:
            # Convert lists to numpy arrays, keep other types as-is
            if isinstance(value, list):
                # Try to convert to float32 array, fallback to object array
                try:
                    arr = np.array(value, dtype=np.float32)
                    pkl_data[json_key] = arr
                except (ValueError, TypeError):
                    # If conversion fails, keep as list or convert to object array
                    pkl_data[json_key] = value
            else:
                pkl_data[json_key] = value
    
    # Handle images -> his_cam_* mapping (current frame)
    # Camera order: CAM_FRONT, CAM_FRONT_RIGHT, CAM_FRONT_LEFT, CAM_BACK, CAM_BACK_LEFT, CAM_BACK_RIGHT
    if 'images' in data and isinstance(data['images'], list):
        images = data['images']
        camera_fields = [
            'his_cam_front',        # index 0: CAM_FRONT
            'his_cam_front_right',  # index 1: CAM_FRONT_RIGHT
            'his_cam_front_left',   # index 2: CAM_FRONT_LEFT
            'his_cam_back',         # index 3: CAM_BACK
            'his_cam_back_left',    # index 4: CAM_BACK_LEFT
            'his_cam_back_right'    # index 5: CAM_BACK_RIGHT
        ]
        
        for i, cam_field in enumerate(camera_fields):
            if i < len(images):
                img_path = images[i]
                # Convert string path to bytes for TensorFlow constant
                if isinstance(img_path, str):
                    pkl_data[cam_field] = tf.constant(img_path.encode('utf-8'))
                else:
                    pkl_data[cam_field] = tf.constant(img_path)
            else:
                pkl_data[cam_field] = tf.constant(b'')
    
    # Handle his_images -> his_cam_*_time mapping (previous frame, all views)
    # Camera order: CAM_FRONT, CAM_FRONT_RIGHT, CAM_FRONT_LEFT, CAM_BACK, CAM_BACK_LEFT, CAM_BACK_RIGHT
    if 'his_images' in data and isinstance(data['his_images'], list):
        his_images = data['his_images']
        camera_time_fields = [
            'his_cam_front_time',        # index 0: CAM_FRONT
            'his_cam_front_right_time',  # index 1: CAM_FRONT_RIGHT
            'his_cam_front_left_time',   # index 2: CAM_FRONT_LEFT
            'his_cam_back_time',         # index 3: CAM_BACK
            'his_cam_back_left_time',    # index 4: CAM_BACK_LEFT
            'his_cam_back_right_time'    # index 5: CAM_BACK_RIGHT
        ]
        
        for i, cam_field in enumerate(camera_time_fields):
            if i < len(his_images):
                img_path = his_images[i]
                # Convert string path to bytes for TensorFlow constant
                if isinstance(img_path, str):
                    pkl_data[cam_field] = tf.constant(img_path.encode('utf-8'))
                else:
                    pkl_data[cam_field] = tf.constant(img_path)
            else:
                pkl_data[cam_field] = tf.constant(b'')
    
    # Handle status from filename
    json_filename = os.path.basename(json_path)
    status = json_filename.replace('.json', '')
    pkl_data['status'] = status
    
    # Save to pkl
    if output_path is None:
        output_path = json_path.replace('.json', '.pkl')
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'wb') as f:
        pickle.dump(pkl_data, f)
    
    return pkl_data

def convert_directory(json_dir, output_dir=None):
    """
    Convert all JSON files in a directory to pkl format.
    
    Args:
        json_dir: Directory containing JSON files
        output_dir: Output directory for pkl files (if None, use same directory)
    """
    json_dir = Path(json_dir)
    if output_dir is None:
        output_dir = json_dir
    else:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
    
    json_files = list(json_dir.glob('*.json'))
    for json_file in tqdm(json_files, desc=f"Converting in {json_dir}", unit="file"):
        try:
            output_file = output_dir / json_file.name.replace('.json', '.pkl')
            convert_json_to_pkl(json_file, output_file)
            print(f"Converted: {json_file.name} -> {output_file.name}")
        except Exception as e:
            print(f"Error converting {json_file.name}: {e}")

if __name__ == '__main__':
    import argparse
    
    parser = argparse.ArgumentParser(description='Convert JSON files to pkl format for drive-π0')
    parser.add_argument('input', type=str, help='Input JSON file or directory')
    parser.add_argument('--output', type=str, default=None, help='Output pkl file or directory')
    parser.add_argument('--recursive', action='store_true', help='Recursively process directories')
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    
    if input_path.is_file():
        # Single file conversion
        convert_json_to_pkl(input_path, args.output)
    elif input_path.is_dir():
        # Directory conversion
        if args.recursive:
            all_json_files = list(input_path.rglob('*.json'))
            for json_file in tqdm(all_json_files, desc=f"Converting in {input_path}", unit="file"):
                rel_path = json_file.relative_to(input_path)
                if args.output:
                    output_file = Path(args.output) / rel_path.with_suffix('.pkl')
                else:
                    output_file = json_file.with_suffix('.pkl')
                output_file.parent.mkdir(parents=True, exist_ok=True)
                try:
                    convert_json_to_pkl(json_file, output_file)
                except Exception as e:
                    print(f"Error converting {json_file}: {e}")
        else:
            convert_directory(input_path, args.output)
    else:
        print(f"Error: {input_path} is not a valid file or directory")

